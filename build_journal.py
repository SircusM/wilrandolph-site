def esc(s: str) -> str:
    return html.escape(s, quote=True)


def post_url(post: dict) -> str:
    return f"{SITE_URL}/journal/{post['id']}.html"


def share_bar(post: dict) -> str:
    """Share links that pass this post's unique permalink to each network."""
    url = post_url(post)
    u = quote(url, safe="")
    t = quote(post["title"], safe="")
    body = quote(f"{post['excerpt']}\n\n{url}", safe="")
    return (
        '<div class="wr-share">'
        '<span class="wr-share-label">Share</span>'
        f'<a href="https://www.linkedin.com/sharing/share-offsite/?url={u}" target="_blank" rel="noopener" aria-label="Share on LinkedIn">{ICONS["linkedin"]}LinkedIn</a>'
        f'<a href="https://twitter.com/intent/tweet?url={u}&amp;text={t}" target="_blank" rel="noopener" aria-label="Share on X">{ICONS["x"]}X</a>'
        f'<a href="https://www.facebook.com/sharer/sharer.php?u={u}" target="_blank" rel="noopener" aria-label="Share on Facebook">{ICONS["facebook"]}Facebook</a>'
        f'<a href="mailto:?subject={t}&amp;body={body}" aria-label="Share by email">{ICONS["email"]}Email</a>'
        f'<button type="button" class="wr-copy-btn" data-url="{esc(url)}">{ICONS["link"]}<span>Copy Link</span></button>'
        "</div>"
    )


def json_ld(post: dict) -> str:
    data = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": post["title"],
        "description": post["excerpt"],
        "image": post["image"],
        "datePublished": post["date"],
        "author": {"@type": "Person", "name": "Wil Randolph", "url": SITE_URL},
        "publisher": {"@type": "Person", "name": "Wil Randolph"},
        "mainEntityOfPage": post_url(post),
    }
    return json.dumps(data, indent=2).replace("</", "<\\/")


def cat_tags(post: dict) -> str:
    return "".join(f'<span class="wr-cat-tag">{esc(c)}</span>' for c in post["categories"])


