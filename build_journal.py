def rewrite_journal_html(posts: list) -> None:
    """Regenerate the POSTS data block and OG meta block inside journal.html."""
    path = ROOT / "journal.html"
    src = path.read_text(encoding="utf-8")

    posts_js = json.dumps(posts, indent=2, ensure_ascii=False).replace("</", "<\\/")
    block = f"/* POSTS:BEGIN — generated from posts.json by build_journal.py. Do not edit by hand. */\nvar POSTS = {posts_js};\n/* POSTS:END */"
    new = re.sub(
        r"/\* POSTS:BEGIN[\s\S]*?/\* POSTS:END \*/",
        lambda _: block,
        src,
        count=1,
    )
    if new == src and "/* POSTS:BEGIN" not in src:
        sys.exit("ERROR: POSTS:BEGIN/END markers not found in journal.html")

    latest = posts[0]
    og = (
        "<!-- OG:BEGIN — generated by build_journal.py -->\n"
        '<meta property="og:type" content="website">\n'
        '<meta property="og:site_name" content="Wil Randolph — Brand &amp; Marketing Strategist">\n'
        '<meta property="og:title" content="Journal — Wil Randolph">\n'
        '<meta property="og:description" content="Writing on brand strategy, marketing practice, creative leadership, AEC marketing, AI integration, and the business of building things that last.">\n'
        f'<meta property="og:url" content="{SITE_URL}/journal.html">\n'
        f'<meta property="og:image" content="{esc(latest["image"])}">\n'
        '<meta name="twitter:card" content="summary_large_image">\n'
        "<!-- OG:END -->"
    )
    new2 = re.sub(r"<!-- OG:BEGIN[\s\S]*?<!-- OG:END -->", lambda _: og, new, count=1)
    if new2 == new and "<!-- OG:BEGIN" not in new:
        sys.exit("ERROR: OG:BEGIN/END markers not found in journal.html")

    path.write_text(new2, encoding="utf-8")


def main() -> None:
    posts = json.loads((ROOT / "posts.json").read_text(encoding="utf-8"))
    if not posts:
        sys.exit("ERROR: posts.json is empty")

    seen = set()
    for p in posts:
        for field in ("id", "title", "date", "dateDisplay", "categories", "image", "excerpt", "body"):
            if field not in p:
                sys.exit(f"ERROR: post '{p.get('id', '?')}' is missing field '{field}'")
        if p["id"] in seen:
            sys.exit(f"ERROR: duplicate post id '{p['id']}'")
        seen.add(p["id"])
        if not p["image"]:
            print(f"WARNING: post '{p['id']}' has no image — social previews will have no picture")

    JOURNAL_DIR.mkdir(exist_ok=True)

    for p in posts:
        (JOURNAL_DIR / f"{p['id']}.html").write_text(render_post_page(p), encoding="utf-8")
    print(f"Generated {len(posts)} post pages in journal/")

    # Remove stale generated pages for posts no longer in posts.json
    for f in JOURNAL_DIR.glob("*.html"):
        if f.stem not in seen and FINGERPRINT in f.read_text(encoding="utf-8"):
            f.unlink()
            print(f"Removed stale page journal/{f.name}")

    rewrite_journal_html(posts)
    print("Updated journal.html (POSTS data + OG meta)")
    print("Done. Commit and push to GitHub — Vercel deploys automatically.")


if __name__ == "__main__":
    main()
